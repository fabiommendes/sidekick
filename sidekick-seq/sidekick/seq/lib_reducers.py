# Special reductions
#
def product(seq: Iterable[num], /, init: num = 1) -> num:
    """
    Multiply all elements of sequence.

    Examples:
        >>> sk.product([1, 2, 3, 4, 5])
        120

    See also:
        :func:`products`
        :func:`sum`
    """
    for x in seq:
        init = x * init
    return init


def sum(seq: Iterable[num], /, init: num = 0) -> num:
    """
    Sum all arguments of sequence.

    It exists only in symmetry with :func:`product`, since Python already
    has a builtin sum function that behaves identically.

    Examples:
        >>> sk.sum([1, 2, 3, 4, 5])
        15

    See also:
        :func:`sums`
        :func:`product`
    """
    return _sum(seq, init)


def products(seq: Iterable[num], /, *, init: num = 1) -> iter[num]:
    """
    Return a sequence of partial products.

    Examples:
        >>> sk.products([1, 2, 3, 4, 5])
        sk.iter([1, 2, 6, 24, 120])

    See also:
        :func:`acc`
        :func:`sums`
    """
    return iter(_products(seq, init))


def _products(seq, init):
    for x in seq:
        init = x * init
        yield init


def sums(seq: Iterable[num], /, *, init: num = 0) -> iter[num]:
    """
    Return a sequence of partial sums.

    Same as ``sk.fold((X + Y), seq, 0)``

    Examples:
        >>> sk.sums([1, 2, 3, 4, 5])
        sk.iter([1, 3, 6, 10, 15])

    See also:
        :func:`acc`
        :func:`products`
    """
    return iter(_sums(seq, init))


def _sums(seq, init):
    for x in seq:
        init = x + init
        yield init


def all_by(pred: Pred[a], seq: Iterable[a], /) -> bool:
    """
    Return True if all elements of seq satisfy predicate.

    ``all_by(None, seq)`` is the same as the builtin ``all(seq)`` function.

    Examples:
        >>> sk.all_by((X % 2), [1, 3, 5])
        True

    See also:
        :func:`any_by`
    """
    return all(map(to_callable(pred), seq))


def any_by(pred: Pred[a], seq: Iterable[a], /) -> bool:
    """
    Return True if any elements of seq satisfy predicate.

    ``any_by(None, seq)`` is the same as the builtin ``any(seq)`` function.

    Examples:
        >>> sk.any_by(sk.is_divisible_by(2), [2, 3, 5, 7, 11, 13])
        True

    See also:
        :func:`all_by`
    """
    return any(map(to_callable(pred), seq))


def top_k(
    k: int, seq: Iterable[a], /, *, key: Callable[[a], b] = NOT_GIVEN
) -> tuple[a, ...]:
    """
    Find the k largest elements of a sequence.

    Examples:
        >>> sk.top_k(3, "hello world")
        ('w', 'r', 'o')
    """
    kwargs = {} if key is NOT_GIVEN else {"key": key}
    return toolz.topk(k, seq, **kwargs)
