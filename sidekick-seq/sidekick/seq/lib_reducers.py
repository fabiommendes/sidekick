# Basic reductions and folds
#
def fold(func: FoldOp[b, a], init: b, seq: Iterable[a], /) -> b:
    """
    Perform a left reduction of sequence.

    Examples:
        >>> sk.fold(op.add, 0, [1, 2, 3, 4])
        10

    See also:
        :func:`reduce`
        :func:`scan`
    """
    func = to_callable(func)
    return _reduce(func, seq, init)


def reduce(
    func: BinOp[a], seq: Iterable[a], /, initial: a = NOT_GIVEN, default: a = NOT_GIVEN
) -> a:
    """
    Similar to fold, but does not require initial value.

    This function raises a ValueError on empty sequences.

    Args:
        func:
            A binary operator over items in the sequence.
        seq:
            The sequence of elements
        initial:
            Exists for compatibility with the builtin reduce function.
            If you need to set up this value, use :func:`fold` instead.
        default:
            Default value returned for empty sequences. Default is *not*
            used as the initial value of a fold, and is only returned on
            empty sequences.

    Examples:
        >>> sk.reduce(op.add, [1, 2, 3, 4])
        10

    See also:
        :func:`fold`
        :func:`acc`
    """
    if initial is not NOT_GIVEN:
        warnings.warn("use the sk.fold() function to set initial values.")
        return fold(func, initial, seq)

    func = to_callable(func)
    seq = _iter(seq)
    try:
        initial = next(seq)
    except StopIteration:
        if default is NOT_GIVEN:
            raise ValueError("empty sequence")
        return default
    return _reduce(func, seq, initial)


def scan(func: Callable[[b, a], b], init: b, seq: Iterable[a], /) -> iter[b]:
    """
    Returns a sequence of the intermediate folds of seq by func.

    In other words it generates a sequence like:

        func(init, seq[0]), func(result[0], seq[1]), ...

    in which result[i] corresponds to items in the resulting sequence.pyte

    See also:
        :func:`acc`
        :func:`fold`
    """
    func = to_callable(func)
    return iter(toolz.accumulate(func, seq, init))


def acc(func: BinOp[a], seq: Iterable[a], /) -> iter[a]:
    """
    Like :func:`scan`, but uses first item of sequence as initial value.

    See also:
        :func:`scan`
        :func:`reduce`
    """
    func = to_callable(func)
    return iter(toolz.accumulate(func, seq))


def fold_by(
    key: Callable[[a], hashable], op: FoldOp[b, a], init: b, seq: Iterable[a], /
) -> dict[hashable, b]:
    """
    Reduce each sequence generated by a group by.

    More efficient than performing separate operations since it does not
    store intermediate groups.

    Examples:
        >>> sk.fold_by(X % 2, op.add, 0, [1, 2, 3, 4, 5])
        {1: 9, 0: 6}

    See also:
        :func:`fold`
        :func:`group_by`
        :func:`reduce_by`
    """
    return toolz.reduceby(key, op, seq, init)


